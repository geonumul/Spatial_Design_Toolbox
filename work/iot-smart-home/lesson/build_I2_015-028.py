# ---------- 장면 도우미 ----------
def say(*lines):
    return {"kind": "say", "lines": list(lines)}

def pts(head, *items):
    return {"kind": "points", "head": head, "items": list(items)}

def ana(head, scene, pairs):
    return {"kind": "analogy", "head": head, "scene": scene, "map": [list(p) for p in pairs]}

def fig(head, svg, caption, builds):
    return {"kind": "figure", "head": head, "svg": svg, "caption": caption, "builds": builds}

def cmp(head, cols, rows):
    return {"kind": "compare", "head": head, "cols": cols, "rows": [list(r) for r in rows]}

def steps(head, st, answer, given=None):
    d = {"kind": "steps", "head": head, "steps": list(st), "answer": answer}
    if given:
        d["given"] = given
    return d

def chk(q, choices, a, why):
    return {"kind": "check", "q": q, "choices": list(choices), "a": a, "why": why}

def look(head, *boxes):
    bs = []
    for x0, y0, x1, y1, s in boxes:
        bs.append({"x": round(x0 / W, 3), "y": round(y0 / H, 3),
                   "w": round((x1 - x0) / W, 3), "h": round((y1 - y0) / H, 3), "say": s})
    return {"kind": "look", "head": head, "boxes": bs}

def bg(src, *lines):
    return {"kind": "bg", "src": src, "lines": list(lines)}

def exam(src, q, qko, solve, answer):
    return {"kind": "exam", "src": src, "q": q, "qko": qko, "solve": list(solve), "answer": answer}

def eng(head, en, ko, tip=None):
    d = {"kind": "english", "head": head, "en": en, "ko": ko}
    if tip:
        d["tip"] = tip
    return d

def warn(head, *items):
    return {"kind": "warn", "head": head, "items": list(items)}

def goal(*items):
    return {"kind": "goal", "items": list(items)}

def title(big, sub):
    return {"kind": "title", "big": big, "sub": sub}


# ---------- SVG 도우미 ----------
def _b(cls, b):
    return f"{cls} b{b}" if b else cls

def R(x, y, w, h, cls="n", b=None):
    return f'<rect class="{_b(cls, b)}" x="{x}" y="{y}" width="{w}" height="{h}" rx="3"/>'

def T(x, y, s, cls="t", size=16, anchor="middle", b=None):
    return f'<text class="{_b(cls, b)}" x="{x}" y="{y}" font-size="{size}" text-anchor="{anchor}">{s}</text>'

def A(x1, y1, x2, y2, cls="e2", b=None, head=True):
    import math
    ang = math.atan2(y2 - y1, x2 - x1)
    L = 9
    bx, by = x2 - L * math.cos(ang), y2 - L * math.sin(ang)
    out = f'<line class="{_b(cls, b)}" x1="{x1}" y1="{y1}" x2="{bx:.1f}" y2="{by:.1f}"/>'
    if head:
        p1 = (x2, y2)
        p2 = (bx + 5 * math.sin(ang), by - 5 * math.cos(ang))
        p3 = (bx - 5 * math.sin(ang), by + 5 * math.cos(ang))
        pts_ = " ".join(f"{a:.1f},{c:.1f}" for a, c in (p1, p2, p3))
        out += f'<polygon class="{_b("arrow", b)}" points="{pts_}"/>'
    return out

def SVG(*els, h=270):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 480 {h}">' + "".join(els) + "</svg>"


