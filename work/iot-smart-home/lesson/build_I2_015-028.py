def clean(s):
    for a, b in ((chr(0x2014), ", "), (chr(0x2013), "-"), (chr(0xB7), ", "), (chr(0x30FB), ", ")):
        s = s.replace(a, b)
    return s


def glossary():
    d = json.load(open(DICT, encoding="utf-8"))
    out = []
    for ko, en in GLOSS_KEYS:
        hit = [t for t in d if (t.get("ko") or "") == ko and (t.get("en") or "") == en]
        if not hit:
            sys.exit(f"사전에 없음: {ko} | {en}")
        t = hit[0]
        g = {"ko": ko, "en": en, "say": clean(t["say"])}
        more = t.get("more") or t.get("def")
        if more:
            g["more"] = clean(more)
        out.append(g)
    return out


