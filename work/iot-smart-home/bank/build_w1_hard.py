bank = []
cnt = {}


def nid(t):
    cnt[t] = cnt.get(t, 0) + 1
    return f"w1h-{t}-{cnt[t]:03d}"


def base(t, unit, slides):
    return {"id": nid(t), "type": t, "part": "1", "level": "hard", "unit": unit, "slides": slides}


def mcq(unit, slides, q, c, a, e):
    assert len(c) == 4 and 0 <= a < 4
    d = base("mcq", unit, slides)
    d.update(q=q, c=c, a=a, e=e)
    bank.append(d)


def ox(unit, slides, q, a, e):
    d = base("ox", unit, slides)
    d.update(q=q, a=a, e=e)
    bank.append(d)


def short(unit, slides, q, a, e, num=False, tol=None):
    d = base("short", unit, slides)
    d.update(q=q, a=a, e=e)
    if num:
        d["num"] = True
        d["tol"] = tol
    bank.append(d)


def essay(unit, slides, model, q, qko, answer, answer_ko, points):
    assert 4 <= len(points) <= 10
    d = base("essay", unit, slides)
    d.update(model=model, q=q, qko=qko, answer=answer, answer_ko=answer_ko, points=points)
    bank.append(d)


def calc(unit, slides, model, q, qko, blanks, steps, answer, e):
    assert 1 <= len(blanks) <= 6 and 3 <= len(steps) <= 8
    d = base("calc", unit, slides)
    d.update(model=model, q=q, qko=qko, blanks=blanks, steps=steps, answer=answer, e=e)
    bank.append(d)


