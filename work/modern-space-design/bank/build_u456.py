def build():
    out = []
    for part, U in (("4", U4), ("5", U5), ("6", U6)):
        for t in ("mcq", "ox", "short", "essay"):
            for n, row in enumerate(U[t], 1):
                qid = f"u{part}-{t}-{n:03d}"
                if t == "mcq":
                    unit, q, c, e = row
                    order = list(range(4))
                    random.Random(int(hashlib.md5(qid.encode()).hexdigest()[:8], 16)).shuffle(order)
                    out.append({"id": qid, "type": "mcq", "part": part, "unit": unit, "q": q,
                                "c": [c[i] for i in order], "a": order.index(0), "e": e, "level": "basic"})
                elif t == "ox":
                    unit, q, a, e = row
                    out.append({"id": qid, "type": "ox", "part": part, "unit": unit, "q": q, "a": a, "e": e, "level": "basic"})
                elif t == "short":
                    unit, q, a, e = row
                    out.append({"id": qid, "type": "short", "part": part, "unit": unit, "q": q, "a": a, "e": e, "level": "basic"})
                else:
                    unit, q, pts, ans = row
                    out.append({"id": qid, "type": "essay", "part": part, "unit": unit, "q": q, "points": pts, "answer": ans, "level": "basic"})
