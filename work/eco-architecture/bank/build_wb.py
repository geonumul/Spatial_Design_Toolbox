def chk(name, computed, expected, tol=1e-6):
    assert abs(float(computed) - float(expected)) <= tol, f"{name}: computed {computed} != expected {expected}"
    return expected


def base(t, unit, q, **kw):
    d = {"type": t, "part": "b", "level": "basic", "unit": unit, "q": q}
    d.update(kw)
    return d


def mcq(unit, q, c, a, e, **kw):
    return base("mcq", unit, q, c=c, a=a, e=e, **kw)


def ox(unit, q, a, e, **kw):
    return base("ox", unit, q, a=a, e=e, **kw)


def short(unit, q, a, e, **kw):
    return base("short", unit, q, a=a, e=e, **kw)


def essay(unit, q, qko, answer, answer_ko, points, model, e=None, **kw):
    d = base("essay", unit, q, qko=qko, answer=answer, answer_ko=answer_ko, points=points, model=model, **kw)
    if e:
        d["e"] = e
    return d


def calc(unit, q, qko, blanks, steps, answer, e, model, **kw):
    return base("calc", unit, q, qko=qko, blanks=blanks, steps=steps, answer=answer, e=e, model=model, **kw)


