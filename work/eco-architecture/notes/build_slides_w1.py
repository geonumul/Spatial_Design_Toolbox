# ---------- 용어 표기 ----------
def b(ko, en):
    return f"**{ko}({en})**"


def term(ko, en, say):
    return {"ko": ko, "en": en, "say": say}


# ---------- 슬라이드 ----------
def title(big, sub):
    assert len(big) <= 20, big
    return {"kind": "title", "big": big, "sub": sub}


def goal(*items):
    return {"kind": "goal", "items": list(items)}


def points(head, *items):
    return {"kind": "points", "head": head, "items": list(items)}


def analogy(head, scene, *pairs):
    return {"kind": "analogy", "head": head, "scene": scene, "map": [list(p) for p in pairs]}


def figure(head, svg, caption):
    nums = [int(n) for n in re.findall(r"\bb(\d)\b", svg)]
    return {"kind": "figure", "head": head, "svg": svg, "caption": caption, "builds": max(nums) if nums else 1}


def compare(head, cols, *rows):
    return {"kind": "compare", "head": head, "cols": list(cols), "rows": [list(r) for r in rows]}


def steps(head, given, st, answer):
    return {"kind": "steps", "head": head, "given": given, "steps": list(st), "answer": answer}


def check(q, choices, a, why):
    return {"kind": "check", "q": q, "choices": list(choices), "a": a, "why": why}


def warn(head, *items):
    return {"kind": "warn", "head": head, "items": list(items)}


def recap(*items):
    return {"kind": "recap", "items": list(items)}


# ---------- SVG 도우미 (클래스로만 꾸밈, rx 2) ----------
def _c(c, bn):
    return c + (f" b{bn}" if bn else "")


def _w(s, fs):
    return sum(fs * 0.58 if ord(ch) < 0x1100 else fs * 1.0 for ch in s)


def R(x, y, w, h, c="box", bn=0):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="2" class="{_c(c, bn)}"/>'


def X(x, y, s, c="t", fs=15, bn=0, a="middle"):
    if a == "middle":
        assert _w(s, fs) <= 470, s
    return f'<text x="{x}" y="{y}" font-size="{fs}" text-anchor="{a}" class="{_c(c, bn)}">{html.escape(s, quote=False)}</text>'


def L(x1, y1, x2, y2, c="e", bn=0):
    return f'<line x1="{x1:.0f}" y1="{y1:.0f}" x2="{x2:.0f}" y2="{y2:.0f}" class="{_c(c, bn)}"/>'


def A(x1, y1, x2, y2, bn=0, c="e2"):
    dx, dy = x2 - x1, y2 - y1
    d = (dx * dx + dy * dy) ** 0.5
    ux, uy = dx / d, dy / d
    bx, by = x2 - ux * 9, y2 - uy * 9
    px, py = -uy * 5, ux * 5
    return (L(x1, y1, bx, by, c, bn)
            + f'<polygon points="{x2:.0f},{y2:.0f} {bx + px:.0f},{by + py:.0f} {bx - px:.0f},{by - py:.0f}" class="{_c("arrow", bn)}"/>')


def C(cx, cy, r, c="n", bn=0):
    return f'<circle cx="{cx}" cy="{cy}" r="{r}" class="{_c(c, bn)}"/>'


def P(pts, c="n", bn=0):
    return f'<polygon points="{pts}" class="{_c(c, bn)}"/>'


def BX(x, y, w, h, label, c="box", tc="tb", fs=15, bn=0):
    assert _w(label, fs) <= w - 4, (label, _w(label, fs), w)
    return R(x, y, w, h, c, bn) + X(x + w / 2, y + h / 2 + fs * 0.35, label, tc, fs, bn)


def SVG(*els, h=270):
    return f'<svg viewBox="0 0 480 {h}" xmlns="http://www.w3.org/2000/svg">' + "".join(els) + "</svg>"


