def T(ko, en, say):
    return {"ko": ko, "en": en, "say": say}


def title(big, sub):
    assert len(big) <= 20, big
    return {"kind": "title", "big": big, "sub": sub}


def goal(*items):
    return {"kind": "goal", "items": list(items)}


def pts(head, *items):
    return {"kind": "points", "head": head, "items": list(items)}


def where(*items):
    return pts("이게 이 과목 어디에 나오나", *items)


def ana(head, scene, *pairs):
    return {"kind": "analogy", "head": head, "scene": scene, "map": [list(p) for p in pairs]}


def fig(head, svg, caption):
    nums = [int(m) for m in re.findall(r"\bb(\d)\b", svg)]
    return {"kind": "figure", "head": head, "svg": svg, "caption": caption, "builds": max(nums) if nums else 1}


def formula(head, tex, parts, whole):
    return {"kind": "formula", "head": head, "tex": tex,
            "parts": [{"sym": s, "say": w} for s, w in parts], "whole": whole}


def steps(head, given, st, answer):
    d = {"kind": "steps", "head": head}
    if given:
        d["given"] = given
    d["steps"] = list(st)
    d["answer"] = answer
    return d


def cmp(head, cols, *rows):
    return {"kind": "compare", "head": head, "cols": list(cols), "rows": [list(r) for r in rows]}


def eng(head, en, ko, tip=None):
    d = {"kind": "english", "head": head, "en": en, "ko": ko}
    if tip:
        d["tip"] = tip
    return d


def chk(q, choices, a, why):
    return {"kind": "check", "q": q, "choices": list(choices), "a": a, "why": why}


def warn(head, *items):
    return {"kind": "warn", "head": head, "items": list(items)}


def recap(*items):
    return {"kind": "recap", "items": list(items)}


def unit(uid, utitle, ugoal, terms, slides):
    UNITS.append({"id": uid, "title": utitle, "goal": ugoal, "terms": terms, "slides": slides})


