def _c(c, b):
    return f"{c} b{b}" if b else c


def S(*els, h=270):
    return f'<svg viewBox="0 0 480 {h}" xmlns="http://www.w3.org/2000/svg">' + "".join(els) + "</svg>"


def R(x, y, w, h, c="box", b=0, rx=2):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" class="{_c(c, b)}"/>'


def C(x, y, r, c="n", b=0):
    return f'<circle cx="{x}" cy="{y}" r="{r}" class="{_c(c, b)}"/>'


def L(x1, y1, x2, y2, c="e", b=0):
    return f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" class="{_c(c, b)}"/>'


def X(x, y, s, c="t", b=0, fs=15, a="middle"):
    return f'<text x="{x}" y="{y}" font-size="{fs}" text-anchor="{a}" class="{_c(c, b)}">{escape(s)}</text>'


def PG(points, c="n", b=0):
    return f'<polygon points="{points}" class="{_c(c, b)}"/>'


def PL(points, c="e", b=0):
    return f'<polyline points="{points}" fill="none" class="{_c(c, b)}"/>'


def A(x1, y1, x2, y2, c="e2", b=0, head=9):
    """선 + 화살촉. (x2, y2) 가 화살촉 끝."""
    dx, dy = x2 - x1, y2 - y1
    d = math.hypot(dx, dy)
    ux, uy = dx / d, dy / d
    bx, by = x2 - ux * head, y2 - uy * head
    px, py = -uy * head * 0.55, ux * head * 0.55
    pts_ = f"{x2:.0f},{y2:.0f} {bx + px:.0f},{by + py:.0f} {bx - px:.0f},{by - py:.0f}"
    return L(x1, y1, f"{bx:.0f}", f"{by:.0f}", c, b) + PG(pts_, "arrow", b)


